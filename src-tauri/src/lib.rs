// The node's core, exposed as a library so integration tests in `tests/` can
// drive it. `main.rs` is the Tauri shell on top: commands, tray and windows.
//
// Before this, `proto` and `grpc_client` were declared only in `main.rs`, which
// meant no `tests/*.rs` target could reach them - and, because `main.rs` also
// declared its own `mod model_manager`, that file was compiled twice into two
// separate crates and its unit tests ran twice.
pub mod catalogue;
pub mod devlog;
pub mod generations;
pub mod model_manager;
pub mod private_file;
pub mod protocol;
pub mod reconnect;
pub mod reload;
pub mod status;
pub mod updater;

// Generated by crates/nodea-proto from protos/service.proto.
pub use nodea_proto as proto;
// The inference crate's request mapping and memory probe, under the names the
// app has always used for them.
pub use nodea_inference::memory;
pub use nodea_inference::request as openai_request;

pub use nodea_inference::node_capabilities;
